/** A real, low-poly globe. Geometry, lighting and occlusion go through the same
 * ASCII render pass as the dragon; the continents are geographical polygons,
 * not an arrangement of decorative points. No runtime remote data request.
 */
export function createEarth() {
	const group = new THREE.Group();
	group.name = "earth";
	const canvas = document.createElement("canvas");
	canvas.width = 2048;
	canvas.height = 1024;
	const context = canvas.getContext("2d")!;
	context.fillStyle = "#124b77";
	context.fillRect(0, 0, canvas.width, canvas.height);
	// Natural Earth 1:110m land, simplified by 0.35 degree Douglas–Peucker.
	// Coordinates below are integer hundredths of a degree, WGS84 lon/lat.
	context.fillStyle = "#dddcb0";
	for (const polygon of LAND) {
		for (const offset of [-2048, 0, 2048]) {
			context.beginPath();
			for (const ring of polygon) {
				let previousX = 0;
				for (let i = 0; i < ring.length; i++) {
					const [longitude, latitude] = ring[i];
					let x = ((longitude / 100 + 180) / 360) * canvas.width;
					const y = ((90 - latitude / 100) / 180) * canvas.height;
					if (i) {
						while (x - previousX > canvas.width / 2) x -= canvas.width;
						while (x - previousX < -canvas.width / 2) x += canvas.width;
					}
					if (i === 0) context.moveTo(x + offset, y);
					else context.lineTo(x + offset, y);
					previousX = x;
				}
				context.closePath();
			}
			context.fill("evenodd");
		}
	}
	const map = new THREE.CanvasTexture(canvas);
	map.colorSpace = THREE.SRGBColorSpace;
	map.minFilter = THREE.LinearMipmapLinearFilter;
	map.magFilter = THREE.LinearFilter;
	map.wrapS = THREE.RepeatWrapping;
	const geometry = new THREE.SphereGeometry(1.7, 48, 24).toNonIndexed();
	const material = new THREE.MeshStandardMaterial({ map, color: 0xa0aaa0, roughness: 0.88, metalness: 0.04, flatShading: true, transparent: true });
	const globe = new THREE.Mesh(geometry, material);
	globe.name = "earth-geographical-surface";
	group.add(globe);
	group.rotation.z = 0.12;
	globe.rotation.y = 2.6;
	return {
		group,
		globe,
		/** Absolute-time rotation avoids accumulating drift and pauses for reduced motion. */
		update(time: number, progress = 0, reduced = false, reveal = 1) {
			globe.rotation.y = 2.6 + (reduced ? 0 : time * 0.13) + progress * 0.25;
			const emergence = THREE.MathUtils.smoothstep(reveal, 0, 1);
			material.opacity = Math.pow(emergence, 2.4);
			// Nonzero derivative through the whole scroll, with a long, slowing tail.
			group.scale.setScalar(0.43 + 0.72 * (1 - Math.exp(-progress * 0.9)) + progress * 0.028);
			group.rotation.z = 0.12 + (1 - emergence) * -0.35;
		},
		dispose() {
			geometry.dispose();
			material.dispose();
			map.dispose();
		}
	};
}

